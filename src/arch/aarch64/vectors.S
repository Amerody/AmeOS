    .section .text.vectors, "ax"
    .balign 0x800
    .global vector_table
vector_table:

    // Current EL with SP0 (not used)
    .balign 0x80
    b   exception_hang  // Synchronous
    .balign 0x80
    b   exception_hang  // IRQ
    .balign 0x80
    b   exception_hang  // FIQ
    .balign 0x80
    b   exception_hang  // SError

    // Current EL with SPx (kernel mode)
    .balign 0x80
    b   sync_el1_handler  // Synchronous
    .balign 0x80
    b   irq_el1_handler   // IRQ ← Our handler
    .balign 0x80
    b   fiq_el1_handler   // FIQ
    .balign 0x80
    b   serror_el1_handler // SError

    // Lower EL (AArch64) 
    .balign 0x80
    b   exception_hang  // Synchronous
    .balign 0x80
    b   exception_hang  // IRQ
    .balign 0x80
    b   exception_hang  // FIQ
    .balign 0x80
    b   exception_hang  // SError

    // Lower EL (AArch32) 
    .balign 0x80
    b   exception_hang  // Synchronous
    .balign 0x80
    b   exception_hang   // IRQ ← Our handler
    .balign 0x80
    b   exception_hang   // FIQ
    .balign 0x80
    b   exception_hang // SError

    .org vector_table + 0x800



